#!/usr/bin/env python3
"""Пересобирает чип выбора режима («ЭПИЗОД 1» / «БЕСКОНЕЧНЫЙ») в плотности K.

Та же болезнь, что была у иконок меню, и то же лечение. Размер чипа задан в
координатах полотна 430×192, а файл автора — 64×64: на телефоне 2400×1080 чип
рисуется примерно в 190 экранных пикселей, то есть втрое крупнее, чем нарисован.
С фильтром NEAREST это и читалось как квадраты; линейный фильтр квадраты убрал,
но резкости взяться было неоткуда.

Разрешения у рисунка не прибавится — исходника крупнее у нас нет. Зато чип
состоит из ДВУХ РАЗНЫХ вещей, и им нужно разное:

  • ПЛАШКА под подпись — прямоугольник с горизонтальными полосами и обводкой в
    один пиксель. Она осепараллельна, поэтому увеличение «по пикселям» (NEAREST)
    сохраняет её ТОЧНО: прямые остаются прямыми, обводка — ровной. Мягкий фильтр,
    наоборот, размывает именно её, и подпись начинает лежать на облаке.
  • РИСУНОК (труба, горящий череп) — мелкая пиксельная графика. Ей NEAREST даёт
    ступеньки, а LANCZOS — ту же мягкость, которую и так давал линейный фильтр
    на экране.

Поэтому чип разбирается на две части, каждая увеличивается своим способом и
собирается обратно. Итог: плашка и обводка резкие, рисунок не хуже прежнего, а
пересэмплирования на экране больше нет — файл теперь крупнее кадра, а не мельче.

Плашка — ЗАМЕР, а не догадка: (11, 40) размером 42×12, одна и та же в обоих
кадрах до пикселя (сверено гистограммой). Скрипт эту разметку проверяет и падает,
если новый чип нарисован иначе, — молча потерять половину рисунка нельзя.

Использование:
    python3 dev/tools/bake_mode_btn.py            # оба чипа
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / 'assets' / 'ui' / 'menu'

# Плотность: сколько пикселей файла на единицу авторского кадра 64×64.
K = 4
UNIT = 64

# Плашка под подпись, в единицах авторского кадра: x, y, ширина, высота.
PLATE = (11, 40, 42, 12)

CHIPS = ['chapter1_mode_btn.png', 'endless_mode_btn.png']


def _check_layout(img: Image.Image, name: str) -> None:
    """Разметка обязана совпасть с замером: ниже плашки и по бокам от неё
    нарисованного быть не должно. Иначе рисунок при разборке потеряется."""
    px = img.load()
    x0, y0, w, h = [v * (img.width // UNIT) for v in PLATE]
    stray = 0
    for y in range(y0, img.height):
        for x in range(img.width):
            if y0 <= y < y0 + h and x0 <= x < x0 + w:
                continue
            if px[x, y][3] > 0:
                stray += 1
    if stray:
        raise SystemExit(f'{name}: {stray} нарисованных пикселей вне замеренной '
                         f'плашки — разметку надо переснять, а не увеличивать')


def bake(name: str) -> None:
    src = Image.open(DIR / name).convert('RGBA')
    if src.width != src.height:
        raise SystemExit(f'{name}: кадр не квадратный')
    d = src.width // UNIT          # в какой плотности пришёл файл
    if src.width != UNIT * d:
        raise SystemExit(f'{name}: кадр {src.width} — не целое число замеров {UNIT}')
    _check_layout(src, name)

    px0, py0, pw, ph = [v * d for v in PLATE]
    plate = src.crop((px0, py0, px0 + pw, py0 + ph))
    art = src.copy()
    # Рисунок — это ВСЁ, кроме плашки: вырезаем её, а не «берём верх кадра», —
    # рисунок может заходить на её строки, и обрезать его по горизонтали значило
    # бы отрезать подбородок черепу.
    art.paste((0, 0, 0, 0), (px0, py0, px0 + pw, py0 + ph))

    out_px = UNIT * K
    plate_big = plate.resize((pw * K // d, ph * K // d), Image.NEAREST)
    art_big = art.resize((out_px, out_px), Image.LANCZOS)

    out = Image.new('RGBA', (out_px, out_px), (0, 0, 0, 0))
    out.alpha_composite(art_big)
    out.alpha_composite(plate_big, (PLATE[0] * K, PLATE[1] * K))
    out.save(DIR / name)
    print(f'{name}: {src.width}×{src.width} → {out_px}×{out_px} '
          f'(плашка по пикселям, рисунок сглаженно)')


if __name__ == '__main__':
    for chip in CHIPS:
        bake(chip)
