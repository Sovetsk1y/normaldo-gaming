#!/usr/bin/env python3
"""Поднимает плотность рисунка предмета в K раз.

Разрешения от этого не прибавляется — детали, которой не было, не появится.
Задача другая: сделать так, чтобы предмет НЕ БЫЛ ЕДИНСТВЕННЫМ, кого на экране
раздувают.

Как это устроено в игре. Все предметы рисуются в размер, заданный `ItemSizing` в
координатах вьюпорта 960×430, а на телефоне весь кадр растягивается ещё раз (у
2400×1080 это ×2.5). Исходники при этом крупные — пицца 511 px рисунка на 52
экранных, собака 355 на 71, — и на телефоне они всё равно УМЕНЬШАЮТСЯ. Так и
задумано: у пиксель-арта запас плотности должен быть, иначе фильтр NEAREST на
дробном масштабе рвёт картинку на неровные квадраты.

Бочка из сет-писа с бомжом была исключением: 107 пикселей рисунка на 88
экранных, то есть на телефоне ×2.05 — единственный предмет в игре, который
раздувают. Рядом с бомжом, чей рисунок в четыре раза плотнее, она читалась
заквадратившейся, и это было правдой: её пиксель буквально втрое крупнее.

Увеличение — LANCZOS, а не «по пикселям». Смысл ровно в том, чтобы ступенек не
осталось: NEAREST их сохранит и мы ничего не добьёмся, а мягкое увеличение даёт
экрану то же, что дал бы более плотный оригинал, — ровный контур. Сравнивали три
варианта на экранном размере: как есть (ступеньки), LANCZOS (ровно, рёбра
различимы) и «по пикселям плюс размытие» (каша).

Рамка кадра растёт вместе с рисунком, поэтому взаимная привязка кадров
сохраняется: `bum_barrel.gd` считает и масштаб, и опору по `content_rect`, и обе
бочки — закрытая и открытая — остаются в одном масштабе.

Использование:
    python3 dev/tools/upscale_item.py <файл.png> [<файл.png> ...] [--k 4]
"""
import sys
from pathlib import Path
from PIL import Image

K = 4


# LANCZOS оставляет вокруг рисунка кольцо почти прозрачных пикселей — «звон»
# фильтра. Глазу его не видно, а вот `Image.get_used_rect()`, по которому
# ItemSizing меряет рисунок, считает непрозрачным всё, у чего альфа больше нуля:
# рамка рисунка от этого разъезжается на пару пикселей, и предмет выходит на
# те же пару пикселей мельче заданного. Отрезаем этот звон порогом.
ALPHA_FLOOR = 6


def upscale(path: Path, k: int) -> None:
    im = Image.open(path).convert('RGBA')
    box = im.getbbox()
    before = (box[2] - box[0], box[3] - box[1]) if box else (0, 0)
    out = im.resize((im.width * k, im.height * k), Image.LANCZOS)
    alpha = out.split()[3].point(lambda a: 0 if a < ALPHA_FLOOR else a)
    out.putalpha(alpha)
    out.save(path)
    box = out.getbbox()
    after = (box[2] - box[0], box[3] - box[1]) if box else (0, 0)
    print(f'{path.name}: кадр {im.width}×{im.height} → {out.width}×{out.height}, '
          f'рисунок {before[0]}×{before[1]} → {after[0]}×{after[1]}')


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if a != '--k']
    k = K
    if '--k' in sys.argv:
        k = int(args.pop(args.index(sys.argv[sys.argv.index('--k') + 1])))
    if not args:
        raise SystemExit(__doc__)
    for p in args:
        upscale(Path(p), k)
