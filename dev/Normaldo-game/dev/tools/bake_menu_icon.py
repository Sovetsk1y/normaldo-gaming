#!/usr/bin/env python3
"""Собирает иконку кнопки главного меню: рисунок на фиолетовой шайбе.

Зачем скрипт, а не «нарисовать в редакторе». Кнопок в меню шесть, и шайба у них
обязана быть ОДНА И ТА ЖЕ: разъехавшийся на пиксель круг или чуть другой ореол
в ряду из четырёх кнопок читается как брак. Часть иконок пришла готовой (СЛОТЫ),
часть собирается здесь из голого рисунка — и шайба должна совпасть с точностью
до пикселя. Поэтому её геометрия и цвета не выдуманы, а СНЯТЫ ЗАМЕРОМ с готовых
иконок из набора автора (`SlotsButton.png` и остальные):

    кадр            55×55, центр (27, 27)
    тёмная заливка  d <= 15.5      #000000 при alpha 191
    кольцо          15.5 < d <= 17.5   #5704EF, alpha 255
    ореол           d > 17.5       #3C02A6 со спадом альфы GLOW (замер по кольцу)

Рисунок кладётся в квадрат ART_PX по длинной стороне и центрируется по кругу —
у авторских иконок он занимает 31–35 px, то есть немного заходит на кольцо.

ПЛОТНОСТЬ (K) — сколько пикселей файла приходится на одну единицу этого замера.
Замер снят с авторской иконки, а она 55×55, то есть K=1. Печём мы при этом в
K=4, файлом 220×220, и вот почему.

Экранный размер иконки задаётся в hud.gd в координатах полотна 430×192
(MENU_ICON_CANVAS = 34) и не зависит от файла вовсе. В окне 960×430 кадр иконки
выходит 76 px, а на телефоне 2400×1080 — около 190: режим растяжения
`canvas_items` рисует всё в пикселях устройства. При K=1 это раздув
55 → 190, то есть ×3.45, и каждый пиксель рисунка становится квадратом в
3–4 пикселя — неровным, потому что 3.45 не целое. Ровно это и читалось как
«иконки заквадратились».

Оригиналы автора при этом 500×500: разрешение не отсутствовало, его выбрасывали
на выпечке. При K=4 те же 190 экранных пикселей берутся из 220 — лёгкое
уменьшение вместо раздува втрое. Экранный размер не меняется НИ НА ПИКСЕЛЬ,
меняется только плотность.

Парная к этому правка — фильтр: в hud.gd иконка рисуется LINEAR, а не NEAREST.
Пиксель файла больше не равен пикселю экрана ни при каком K, и nearest на
дробном масштабе — это и есть те самые квадраты.

ГОТОВЫЕ ИКОНКИ (слоты). У них рисунка отдельным файлом нет — есть только
готовая картинка автора в 55×55, и разрешения в ней больше не станет. Но подложка
у неё НЕ нарисованная, а та же самая, что мы печём, — и вот её пересобрать в K=4
можно: круг, кольцо и ореол считаются формулой, им плотность даётся даром.

Поэтому для таких иконок есть режим `--ready`: рисунок СНИМАЕТСЯ с авторской
подложки (`strip_plate`), увеличивается и садится на свежую подложку в K=4.
Кольцо и ореол — самая заметная часть квадратности, это большие гладкие дуги, —
становятся ровными; сам рисунок резче не станет, но и хуже не будет.

Использование:
    python3 dev/tools/bake_menu_icon.py <исходник.png> <результат.png>
    python3 dev/tools/bake_menu_icon.py --all      # пересобрать весь набор
    python3 dev/tools/bake_menu_icon.py --ready <готовая.png> <результат.png>
"""
import sys
from pathlib import Path
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SRC_DIR = ROOT / 'dev' / 'art' / 'menu_icons'
OUT_DIR = ROOT / 'assets' / 'ui' / 'menu' / 'icons'

# Замер (в единицах авторской иконки 55×55) и ПЛОТНОСТЬ, с которой он печётся.
# Все размеры ниже выводятся из K — руками ни одно из них не правится.
K = 4

SIZE = 55 * K
CENTER = 27.0 * K
R_FILL = 15.5 * K
R_RING = 17.5 * K
ART_PX = 34.0 * K

FILL = (0, 0, 0, 191)
RING = (0x57, 0x04, 0xEF, 255)
GLOW = (0x3C, 0x02, 0xA6)
# Спад альфы ореола по расстоянию от центра — замер по авторским иконкам
# (радиус: альфа). Между узлами линейно, дальше последнего — прозрачно.
# Радиусы здесь — в единицах замера; на плотность их умножает _falloff_scaled().
GLOW_FALLOFF = [(17.5, 255), (18.0, 72), (19.0, 57), (20.0, 45),
                (21.0, 33), (22.0, 23), (23.0, 15), (24.0, 9), (25.0, 4), (26.0, 0)]

# Какой рисунок на какую кнопку и нужна ли ему обводка. Имя результата — это
# НАЗНАЧЕНИЕ кнопки, а не что нарисовано: иконку меняют, а константа в hud.gd
# остаётся на месте.
#
# Обводка — не украшение, а единственный способ показать ТЁМНЫЙ рисунок на почти
# чёрной шайбе: без неё чёрные гаечные ключи и тёмно-синяя шапочка читаются как
# дырка в круге. Так же решено и у автора набора: белый контур есть ровно у одной
# иконки — чёрной, — а у жёлтой короны и зелёной книги его нет и быть не должно,
# он бы съел их собственную обводку.
SET = {
    'settings.png':    ('fist.png',  1),   # НАСТРОЙКИ — чёрный рисунок
    'book.png':        ('book.png',  0),   # КНИГА УЧИТЕЛЯ
    'quests.png':      ('cap.png',   1),   # ЗАДАНИЯ — тёмно-синяя шапочка
    'skins.png':       ('skull.png', 0),   # СКИНЫ
    'leaderboard.png': ('crown.png', 0),   # ЛИДЕРЫ
}


# `d` — расстояние в пикселях ФАЙЛА, а узлы замера — в единицах авторской
# иконки. Кривая одна и та же, растянутая по радиусу в K раз: при K=4 то же
# свечение просто описано вчетверо подробнее.
# Готовые иконки автора: рисунка отдельным файлом нет, пересаживаем с подложки
# на подложку прямо в самом файле (см. `replate`).
READY = ['slots.png']


def _glow_alpha(d: float) -> int:
    for i in range(len(GLOW_FALLOFF) - 1):
        r0, a0 = GLOW_FALLOFF[i]
        r1, a1 = GLOW_FALLOFF[i + 1]
        r0, r1 = r0 * K, r1 * K
        if r0 <= d <= r1:
            k = (d - r0) / (r1 - r0)
            return int(round(a0 + (a1 - a0) * k))
    return 0


# Шайба рисуется в SS раз крупнее и потом усредняется. Круг, посчитанный сразу в
# пикселе, даёт ступенчатое кольцо: у авторской иконки край кольца сглажен, и
# рядом с ней жёсткий круг читался бы как другая кнопка.
SS = 4


def make_plate() -> Image.Image:
    big = Image.new('RGBA', (SIZE * SS, SIZE * SS), (0, 0, 0, 0))
    px = big.load()
    for y in range(SIZE * SS):
        for x in range(SIZE * SS):
            fx = (x + 0.5) / SS - 0.5
            fy = (y + 0.5) / SS - 0.5
            d = ((fx - CENTER) ** 2 + (fy - CENTER) ** 2) ** 0.5
            if d <= R_FILL:
                px[x, y] = FILL
            elif d <= R_RING:
                px[x, y] = RING
            else:
                a = _glow_alpha(d)
                if a:
                    px[x, y] = (*GLOW, a)
    return big.resize((SIZE, SIZE), Image.BOX)


# Белый контур вокруг силуэта рисунка. Считается ПОСЛЕ уменьшения, по итоговым
# пикселям: обведённый в исходном разрешении контур после сжатия в пятнадцать раз
# превратился бы в серую кайму толщиной в полпикселя.
def _outline(art: Image.Image, w: int) -> Image.Image:
    pad = Image.new('RGBA', (art.width + 2 * w, art.height + 2 * w), (0, 0, 0, 0))
    pad.alpha_composite(art, (w, w))
    grown = pad.split()[3].filter(ImageFilter.MaxFilter(2 * w + 1))
    # Порог, а не мягкая кайма: полупрозрачный контур на тёмной шайбе снова
    # становится тёмным и не отделяет рисунок от фона.
    grown = grown.point(lambda p: 255 if p > 96 else 0)
    ring = Image.new('RGBA', pad.size, (255, 255, 255, 255))
    ring.putalpha(grown)
    ring.alpha_composite(pad)
    return ring


def bake(src: Path, out: Path, outline: int = 0) -> None:
    art = Image.open(src).convert('RGBA')
    bbox = art.split()[3].getbbox()
    if bbox is None:
        raise SystemExit(f'{src.name}: пустой рисунок')
    art = art.crop(bbox)
    # Обводка входит В ту же клетку: иначе обведённая иконка вырастала бы в ряду
    # относительно необведённых.
    # Толщина обводки задана в единицах замера (1 = один пиксель авторской
    # иконки), поэтому на плотность её тоже надо умножить: обводка в один
    # пиксель файла при K=4 стала бы вчетверо тоньше нарисованной автором.
    outline = outline * K
    k = (ART_PX - 2 * outline) / max(art.size)
    art = art.resize((max(1, round(art.width * k)), max(1, round(art.height * k))),
                     Image.LANCZOS)
    if outline:
        art = _outline(art, outline)
    icon = make_plate()
    icon.alpha_composite(art, (round(CENTER - art.width / 2),
                               round(CENTER - art.height / 2)))
    icon.save(out)
    print(f'{out.name}: {src.name} → {art.size[0]}×{art.size[1]} на шайбе {SIZE}×{SIZE}')


# ── Готовая иконка: снять рисунок с подложки и пересадить на свежую ─────────
# Рисунок отделяется ВЫЧИТАНИЕМ: авторская иконка — это рисунок, положенный на
# ту же самую подложку, и всё, что от подложки отличается, и есть рисунок.
#
# Порог мягкий, а не «равно/не равно»: у авторского кольца своё сглаживание, оно
# расходится с нашим на единицы, и жёсткое сравнение вытащило бы вместе с
# рисунком кайму мусора по всему кольцу. Расхождение переводится в АЛЬФУ — мелкие
# отличия (то самое сглаживание) уходят почти в ноль, крупные (белые кости,
# жёлтая корона) остаются целиком, а края рисунка получают ту же мягкость, что
# была у автора.
#
# Сравниваются цвета УМНОЖЕННЫМИ НА АЛЬФУ: заливка подложки — чёрная на 191, и
# чёрный контур рисунка поверх неё отличается только альфой. В обычном RGB такой
# контур неотличим от подложки и вырезался бы дырой.
DIFF_LO = 24.0    # ниже — считаем совпадением с подложкой
DIFF_HI = 120.0   # выше — считаем рисунком целиком


def _premul(c):
    return (c[0] * c[3] // 255, c[1] * c[3] // 255, c[2] * c[3] // 255, c[3])


def strip_plate(icon: Image.Image, plate: Image.Image) -> Image.Image:
    art = Image.new('RGBA', icon.size, (0, 0, 0, 0))
    src, base, dst = icon.load(), plate.load(), art.load()
    for y in range(icon.height):
        for x in range(icon.width):
            c, b = src[x, y], base[x, y]
            pc, pb = _premul(c), _premul(b)
            d = max(abs(pc[i] - pb[i]) for i in range(4))
            k = min(1.0, max(0.0, (d - DIFF_LO) / (DIFF_HI - DIFF_LO)))
            if k > 0.0:
                dst[x, y] = (c[0], c[1], c[2], int(round(c[3] * k)))
    return art


def replate(src: Path, out: Path) -> None:
    icon = Image.open(src).convert('RGBA')
    unit = icon.width          # плотность, в которой пришла авторская иконка
    if icon.width != icon.height:
        raise SystemExit(f'{src.name}: кадр не квадратный')
    # Подложка автора — в ЕГО плотности, наша — в нашей.
    art = strip_plate(icon, _plate_at(unit))
    # Рисунок увеличивается LANCZOS, а не «по пикселям»: он и так показывается
    # крупнее, чем нарисован, и ступеньки от NEAREST — это ровно та квадратность,
    # от которой всё затевалось. Подложка при этом остаётся идеальной: она не
    # увеличена, а посчитана заново.
    art = art.resize((SIZE, SIZE), Image.LANCZOS)
    icon4 = make_plate()
    icon4.alpha_composite(art)
    icon4.save(out)
    print(f'{out.name}: рисунок снят с авторской подложки {unit}×{unit} '
          f'и пересажен на свежую {SIZE}×{SIZE}')


# Подложка в ПРОИЗВОЛЬНОЙ плотности — нужна, чтобы вычесть авторскую (K=1) при
# любом нашем K. Считается той же формулой, что и боевая: другой способ рисовать
# круг означал бы, что вычитаем мы не то, что автор нарисовал.
def _plate_at(size: int) -> Image.Image:
    global K, SIZE, CENTER, R_FILL, R_RING, ART_PX
    keep = (K, SIZE, CENTER, R_FILL, R_RING, ART_PX)
    k = size / 55
    K, SIZE = k, size
    CENTER, R_FILL, R_RING, ART_PX = 27.0 * k, 15.5 * k, 17.5 * k, 34.0 * k
    plate = make_plate()
    K, SIZE, CENTER, R_FILL, R_RING, ART_PX = keep
    return plate


if __name__ == '__main__':
    if len(sys.argv) == 2 and sys.argv[1] == '--all':
        for dst, (src, outline) in SET.items():
            bake(SRC_DIR / src, OUT_DIR / dst, outline)
        for dst in READY:
            replate(OUT_DIR / dst, OUT_DIR / dst)
    elif len(sys.argv) == 4 and sys.argv[1] == '--ready':
        replate(Path(sys.argv[2]), Path(sys.argv[3]))
    elif len(sys.argv) in (3, 4):
        bake(Path(sys.argv[1]), Path(sys.argv[2]),
             int(sys.argv[3]) if len(sys.argv) == 4 else 0)
    else:
        raise SystemExit(__doc__)
